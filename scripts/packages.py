#!/usr/bin/env python3
"""The `vxp/1` packages under experiments/, and the catalogue generated from them.

    scripts/packages.py list                      one package folder per line
    scripts/packages.py profiles <folder>         the campaign's profiles, one per line
    scripts/packages.py targets                   "<folder> <registry repository> <version>" per package
    VXEDGE=<vxedge> scripts/packages.py catalog   write catalog.yaml
    VXEDGE=<vxedge> scripts/packages.py catalog --check [--base <old catalog.yaml>]

`catalog.yaml` is generated, never edited by hand. `--check` fails when the committed file is not
what the packages give. With `--base`, it also fails when a package keeps the version a published
catalogue lists but its digest changed: a changed package needs a new version.
"""
import argparse
import json
import os
import subprocess
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / "catalog.yaml"
REGISTRY = "ghcr.io/vxedge/experiments"
HEADER = (
    "# Generated by scripts/packages.py from experiments/*/vxp.yaml. Do not edit by hand.\n"
    "# Each package is pushed to its `registry` reference by a vxperiments release.\n"
)


def folders():
    """Every package folder, by path from the repository root."""
    return sorted(p.parent.relative_to(ROOT) for p in ROOT.glob("experiments/*/vxp.yaml"))


def load(path):
    with open(path) as f:
        return yaml.safe_load(f)


def profiles(folder):
    """The campaign's profiles, as `campaign plan --profile` names them."""
    entry = load(ROOT / folder / "vxp.yaml")["entry"]
    doc = load(ROOT / folder / entry) or {}
    return list(((doc.get("campaign") or {}).get("profiles") or {}).keys())


def digest(folder):
    """The package digest, as `vxedge pkg inspect` computes it."""
    vxedge = os.environ.get("VXEDGE")
    if not vxedge:
        sys.exit("packages.py: set VXEDGE to the vxedge binary")
    out = subprocess.run(
        [vxedge, "--json", "--chdir", str(ROOT / folder), "pkg", "inspect"],
        check=True, capture_output=True, text=True,
    ).stdout
    return json.loads(out)["digest"]


def entry(folder):
    descriptor = load(ROOT / folder / "vxp.yaml")
    doc = load(ROOT / folder / descriptor["entry"]) or {}
    name = descriptor["id"].split("/", 1)[1]
    hypothesis = doc.get("hypothesis")
    frozen = Path("results") / name / "campaign.json"
    return {
        "alias": name,
        "id": descriptor["id"],
        "version": str(descriptor["version"]),
        "digest": digest(folder),
        "title": descriptor.get("title"),
        "hypothesis": (
            {"id": hypothesis["id"], "statement": hypothesis["statement"]} if hypothesis else None
        ),
        "folder": str(folder),
        "registry": f"{REGISTRY}/{name}:{descriptor['version']}",
        # The frozen campaign to compare a rerun with (`vxedge campaign compare
        # --reference-workspace`), when one is published.
        "frozen_campaign": str(frozen) if (ROOT / frozen).is_file() else None,
    }


def render():
    body = yaml.safe_dump(
        {"packages": [entry(f) for f in folders()]},
        sort_keys=False, default_flow_style=False, allow_unicode=True, width=100,
    )
    return HEADER + body


def catalog(args):
    text = render()
    if not args.check:
        CATALOG.write_text(text)
        print(f"wrote {CATALOG.relative_to(ROOT)}")
        return 0
    errors = []
    if not CATALOG.is_file() or CATALOG.read_text() != text:
        errors.append("catalog.yaml is not current: run `scripts/packages.py catalog` and commit it")
    if args.base:
        base = load(args.base) or {}
        published = {(p["id"], p["version"]): p["digest"] for p in base.get("packages") or []}
        for p in yaml.safe_load(text)["packages"]:
            old = published.get((p["id"], p["version"]))
            if old and old != p["digest"]:
                errors.append(
                    f"{p['id']} {p['version']} changed ({old} -> {p['digest']}): "
                    f"bump `version` in {p['folder']}/vxp.yaml"
                )
    for e in errors:
        print(f"error: {e}", file=sys.stderr)
    return 1 if errors else 0


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="cmd", required=True)
    sub.add_parser("list")
    sub.add_parser("targets")
    p = sub.add_parser("profiles")
    p.add_argument("folder")
    c = sub.add_parser("catalog")
    c.add_argument("--check", action="store_true")
    c.add_argument("--base", type=Path)
    args = parser.parse_args()
    if args.cmd == "list":
        for f in folders():
            print(f)
        return 0
    if args.cmd == "targets":
        for f in folders():
            descriptor = load(ROOT / f / "vxp.yaml")
            name = descriptor["id"].split("/", 1)[1]
            print(f, f"{REGISTRY}/{name}", descriptor["version"])
        return 0
    if args.cmd == "profiles":
        for name in profiles(Path(args.folder)):
            print(name)
        return 0
    return catalog(args)


if __name__ == "__main__":
    sys.exit(main())
